import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const events={},queue=[],filter={value:'Fishing',reset(){this.value='Woodcutting';}};
const document={addEventListener:(name,fn)=>events['document:'+name]=fn,querySelectorAll(selector){if(selector==='.chart-wrap')return [];assert.equal(selector,'form[method=get]');return [filter];}};
runInNewContext(readFileSync(new URL('../public/app.js',import.meta.url),'utf8'),{window:{addEventListener:(name,fn)=>events[name]=fn},document,location:{hash:''},setTimeout:fn=>queue.push(fn)});
assert.ok(events.pageshow);
events.pageshow();
assert.equal(filter.value,'Fishing','Wait until native history state has been restored');
queue.shift()();
assert.equal(filter.value,'Woodcutting','Restore applied values from server HTML');
let submitted=0;
const change=(select,method)=>events['document:change']({target:{matches:()=>select,form:{method,requestSubmit:()=>submitted++}}});
change(true,'get');assert.equal(submitted,1,'View dropdowns must submit their GET form on change');
change(true,'post');assert.equal(submitted,2,'Settings dropdowns must use their existing POST and redirect flow');
change(false,'get');assert.equal(submitted,2,'Text fields must not submit while being edited');
console.log('Navigation: history restoration and URL-based dropdown changes passed');
